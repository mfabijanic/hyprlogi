"""Omarchy integration: a Setup > Haptics menu and system-event hooks.

The menu lives between marker comments in the user's menu extension
(~/.config/omarchy/extensions/omarchy-menu.jsonc), which the Omarchy shell
hot-reloads. It is static JSONC (the shell has no user-defined providers),
so `hyprlogi omarchy install` regenerates it when profiles change.
"""

import json
import logging
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from hyprlogi.config import CONFIG_DIR, SETTINGS_FILE, list_profiles, load_settings, set_active_profile
from hyprlogi.control import PAUSED_FLAG

MENU_FILE = Path.home() / ".config" / "omarchy" / "extensions" / "omarchy-menu.jsonc"
HOOKS_DIR = Path.home() / ".config" / "omarchy" / "hooks"
BEGIN_MARKER = "  // >>> hyprlogi: generated by `hyprlogi omarchy install`, edits are overwritten"
END_MARKER = "  // <<< hyprlogi"
MENU_ROOT = "setup.hyprlogi"

OMARCHY_PROFILE = "omarchy.json"
# (hook, effect, description); effects are MX Master 4 waveform ids
HOOKS = (
    ("battery-low", 7, "pulse when the laptop battery is low"),
    ("theme-set", 8, "pulse when the theme changes"),
)
HOOK_NAME = "hyprlogi"
TEST_EFFECTS = "1 4 8"


def is_omarchy():
    return shutil.which("omarchy") is not None


def hyprlogi_command():
    """Absolute command line for this hyprlogi, usable from the shell and hooks."""
    installed = shutil.which("hyprlogi")
    if installed:
        return shlex.quote(installed)
    script = Path(sys.argv[0]).resolve()
    if script.name == "hyprlogi" and os.access(script, os.X_OK):
        return shlex.quote(str(script))
    if script.name == "hyprlogi.py":
        return f"{shlex.quote(sys.executable)} {shlex.quote(str(script))}"
    return f"{shlex.quote(sys.executable)} -m hyprlogi"


def editor_command():
    """Starts the profile editor as an app of the session, like Omarchy's own launchers."""
    return "uwsm-app -- hyprlogi-gui" if shutil.which("uwsm-app") else "hyprlogi-gui"


def menu_entries(profiles, command):
    """Returns the (id, entry) pairs of the Setup > Haptics menu."""
    settings_path = str(SETTINGS_FILE).replace(str(Path.home()), "$HOME", 1)
    entries = [
        (MENU_ROOT, {"icon": "󰍽", "label": "Haptics", "description": "HyprLogi",
                     "aliases": ["hyprlogi", "haptics"]}),
        (f"{MENU_ROOT}.paused", {
            "icon": "󰏤", "label": "Paused",
            "checked": f'[[ -e "{PAUSED_FLAG}" ]]',
            "action": f"{command} toggle",
        }),
        (f"{MENU_ROOT}.profile", {"icon": "󰈙", "label": "Profile"}),
    ]
    for filename in profiles:
        stem = filename.removesuffix(".json")
        entries.append((f"{MENU_ROOT}.profile.{re.sub(r'[^a-z0-9-]', '-', stem.lower())}", {
            "icon": "󰄬", "label": stem.replace("-", " ").replace("_", " ").title(),
            "checked": f'grep -Eq \'"active_profile": *"{re.escape(filename)}"\' "{settings_path}"',
            "action": f"{command} profile set {shlex.quote(stem)}",
        }))
    entries += [
        (f"{MENU_ROOT}.editor", {"icon": "󰏫", "label": "Profile editor",
                                 "description": "Edit events, effects and profiles",
                                 "action": editor_command()}),
        (f"{MENU_ROOT}.test", {"icon": "󰍽", "label": "Test effects",
                               "action": f"{command} play {TEST_EFFECTS}"}),
        (f"{MENU_ROOT}.edit", {"icon": "", "label": "Edit settings",
                               "action": f'omarchy-launch-config-editor "{settings_path}"'}),
        (f"{MENU_ROOT}.restart", {"icon": "", "label": "Restart service",
                                  "action": "systemctl --user restart hyprlogi.service"}),
    ]
    return entries


def render_menu_block(entries):
    lines = [BEGIN_MARKER]
    lines += [f"  {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)}," for key, value in entries]
    lines.append(END_MARKER)
    return "\n".join(lines) + "\n"


def update_menu_text(text, block):
    """Replaces (or removes, when block is None) the hyprlogi block in a menu JSONC text.

    The block goes right after the opening brace with a trailing comma on
    every entry: the shell drops trailing commas, and the user's own entries
    after it need no change.
    """
    text = re.sub(rf"^{re.escape(BEGIN_MARKER)}\n.*?^{re.escape(END_MARKER)}\n", "",
                  text, flags=re.S | re.M)
    if block is None:
        return text
    if not text.strip():
        return "{\n" + block + "}\n"

    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if not line.lstrip().startswith("//") and "{" in line:
            lines.insert(i + 1, block)
            return "".join(lines)
    raise ValueError(f"{MENU_FILE} has no opening brace")


def install_menu(command, menu_file=MENU_FILE):
    menu_file.parent.mkdir(parents=True, exist_ok=True)
    text = menu_file.read_text() if menu_file.exists() else ""
    menu_file.write_text(update_menu_text(text, render_menu_block(menu_entries(list_profiles(), command))))
    print(f"Menu: Setup > Haptics in {menu_file}")


def uninstall_menu(menu_file=MENU_FILE):
    if menu_file.exists():
        menu_file.write_text(update_menu_text(menu_file.read_text(), None))
        print(f"Removed the Haptics menu from {menu_file}")


def install_hooks(command):
    with tempfile.TemporaryDirectory() as tmp:
        for hook, effect, description in HOOKS:
            script = Path(tmp) / HOOK_NAME
            script.write_text(
                "#!/bin/bash\n"
                f"# Installed by `hyprlogi omarchy install`: {description}.\n"
                f"{command} play {effect} >/dev/null 2>&1 || true\n")
            if is_omarchy():
                subprocess.run(["omarchy", "hook", "install", hook, str(script)], check=True)
            else:
                target = HOOKS_DIR / f"{hook}.d" / HOOK_NAME
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy(script, target)
                target.chmod(0o755)
                print(f"Installed {hook} hook: {target}")


def uninstall_hooks():
    for hook, *_ in HOOKS:
        target = HOOKS_DIR / f"{hook}.d" / HOOK_NAME
        if target.exists():
            target.unlink()
            print(f"Removed {hook} hook: {target}")


PLUGIN_URL = "https://github.com/mfabijanic/hyprlogi-omarchy.git"
PLUGIN_ID = "mfabijanic.hyprlogi"


def install_plugin():
    """Adds and enables the HyprLogi bar widget from git."""
    if not is_omarchy():
        raise ValueError("the bar widget needs the Omarchy shell ('omarchy' command not found)")
    if (Path.home() / ".config" / "omarchy" / "plugins" / PLUGIN_ID).exists():
        print(f"Bar widget {PLUGIN_ID} is already installed (update it with 'omarchy plugin update {PLUGIN_ID}').")
        return
    subprocess.run(["omarchy", "plugin", "add", PLUGIN_URL, "--enable", "--yes"], check=True)


def install(menu=True, hooks=True):
    """Sets up the Omarchy integration; returns True if the active profile changed."""
    command = hyprlogi_command()
    changed = False
    # Switch to the Omarchy profile unless the user picked their own
    if load_settings().get("active_profile") == "default.json":
        set_active_profile(OMARCHY_PROFILE)
        print(f"Active profile: {OMARCHY_PROFILE}")
        changed = True
    if menu:
        install_menu(command)
    if hooks:
        install_hooks(command)
    logging.debug("Omarchy integration installed for %s (config %s)", command, CONFIG_DIR)
    return changed


def uninstall():
    uninstall_menu()
    uninstall_hooks()
